/*
# Products table, sequential order numbers, order status, and merchant lockdown

1. Purpose
Turn the storefront from a hardcoded menu into a database-driven one, add
order tracking for the merchant dashboard, and lock customer data down so
only the signed-in merchant can read orders and receipts.

2. New Tables
- `products`: the storefront menu.
  - `id` (uuid, primary key)
  - `name` (text, not null)
  - `description` (text, not null)
  - `price` (numeric(10,2), not null)
  - `category` (text, not null) — 'signature' | 'drinks' | 'desserts'
  - `image_url` (text, nullable) — future product photos
  - `options` (jsonb, not null, default '[]') — option groups: [{ id, label, required, options: [{ id, label, priceDelta }] }]
  - `emoji` (text, not null, default '🍽️') — visual placeholder until photos exist
  - `accent` (text, not null, default brand gradient) — card gradient classes
  - `tag` (text, nullable) — small badge e.g. "Bestseller"
  - `is_available` (boolean, not null, default true) — sold-out toggle
  - `sort_order` (integer, not null, default 0) — display ordering
  - `created_at` (timestamptz, default now())

3. Modified Tables
- `orders`:
  - ADD `order_number` (integer, unique) — sequential, generated by the DB via
    an identity column starting at 101 (e.g. #ORD-101). Display format is
    '#ORD-' || order_number.
  - ADD `status` (text, not null, default 'pending') — 'pending' | 'verified' |
    'preparing' | 'completed', updated by the merchant from the dashboard.
  - RENAME `total` to `total_amount` (matches app spec; no data loss).
  - RENAME `order_ref` values are preserved; the column stays as a secondary
    human reference but new orders get their identity from order_number.
  - DROP the `order_ref` column's NOT NULL/UNIQUE burden: it becomes nullable
    legacy. Actually kept NOT NULL for existing rows; new writes may omit it
    by making it nullable going forward.

4. Security
- Enable RLS on `products`.
- `products`: public read of AVAILABLE products for the storefront
  (is_available = true) for anon + authenticated; merchant (authenticated)
  may read all rows, update, and insert. Anon cannot update or insert.
- `orders`: customer INSERT stays open to anon (WITH CHECK true). Reading and
  updating order status is restricted TO authenticated (the merchant).
  Anon SELECT is revoked — customer names, phones, addresses, and receipts
  are no longer public.
- Storage `receipts`: anon can still UPLOAD receipts (checkout must work
  without an account), but only the authenticated merchant can READ them;
  the dashboard generates short-lived signed URLs for the receipt modal.
- Column-restricted merchant UPDATE on orders: merchants may only change
  `status` (and nothing else) from the client.
- Grants updated to match: anon gets INSERT on orders and SELECT on products
  (all columns); authenticated gets full product CRUD and order SELECT +
  status-only UPDATE.

5. Seed Data
- Seed the nine existing menu items (Nasi Katok Buttermilk Chicken, Ambuyat
  Set, Nasi Goreng Pattaya, Mee Goreng Basah, Teh Tarik Cincau, Air Limau
  Ais, Sirap Bandung Susu, Kek Batik Indulgence, Punjan & Kuih Lapis) with
  their prices, categories, option groups, and display order. Seeding is
  idempotent, keyed by product name.

6. Notes
- The identity column guarantees unique sequential order numbers under
  concurrent customer checkouts.
- Existing orders (if any) keep their order_ref; order_number will be
  backfilled sequentially for rows that predate this change.
*/

-- 1. Orders table upgrades
ALTER TABLE orders
  ADD COLUMN IF NOT EXISTS order_number integer GENERATED BY DEFAULT AS IDENTITY (START WITH 101 INCREMENT BY 1),
  ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'verified', 'preparing', 'completed'));

ALTER TABLE orders RENAME COLUMN total TO total_amount;

-- order_ref becomes optional legacy: new orders rely on order_number
ALTER TABLE orders ALTER COLUMN order_ref DROP NOT NULL;

-- Backfill order_number for any rows created before this migration
DO $$
DECLARE
  r record;
  next_num integer;
BEGIN
  SELECT COALESCE(MAX(order_number), 100) INTO next_num FROM orders WHERE order_number IS NOT NULL;
  FOR r IN SELECT id FROM orders WHERE order_number IS NULL ORDER BY created_at ASC
  LOOP
    next_num := next_num + 1;
    UPDATE orders SET order_number = next_num WHERE id = r.id;
  END LOOP;
END $$;

-- 2. Products table
CREATE TABLE IF NOT EXISTS products (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  description text NOT NULL,
  price numeric(10,2) NOT NULL,
  category text NOT NULL CHECK (category IN ('signature', 'drinks', 'desserts')),
  image_url text,
  options jsonb NOT NULL DEFAULT '[]',
  emoji text NOT NULL DEFAULT '🍽️',
  accent text NOT NULL DEFAULT 'from-amber-500 to-orange-600',
  tag text,
  is_available boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE products ENABLE ROW LEVEL SECURITY;

-- 3. Grants
-- orders: anon may insert only; merchant may read + update status only
GRANT INSERT ON orders TO anon;
GRANT SELECT ON orders TO authenticated;
GRANT UPDATE (status) ON orders TO authenticated;

-- products: public reads available items; merchant manages everything
GRANT SELECT ON products TO anon, authenticated;
GRANT INSERT, UPDATE ON products TO authenticated;

-- 4. Policies: orders
DROP POLICY IF EXISTS "anon_insert_orders" ON orders;
CREATE POLICY "anon_insert_orders" ON orders
FOR INSERT TO anon WITH CHECK (true);

DROP POLICY IF EXISTS "anon_select_orders" ON orders;
CREATE POLICY "anon_select_orders" ON orders
FOR SELECT TO anon USING (false);

DROP POLICY IF EXISTS "merchant_select_orders" ON orders;
CREATE POLICY "merchant_select_orders" ON orders
FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "merchant_update_order_status" ON orders;
CREATE POLICY "merchant_update_order_status" ON orders
FOR UPDATE TO authenticated
USING (true)
WITH CHECK (true);

-- 5. Policies: products
DROP POLICY IF EXISTS "public_read_available_products" ON products;
CREATE POLICY "public_read_available_products" ON products
FOR SELECT TO anon
USING (is_available = true);

DROP POLICY IF EXISTS "merchant_read_products" ON products;
CREATE POLICY "merchant_read_products" ON products
FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "merchant_insert_products" ON products;
CREATE POLICY "merchant_insert_products" ON products
FOR INSERT TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "merchant_update_products" ON products;
CREATE POLICY "merchant_update_products" ON products
FOR UPDATE TO authenticated
USING (true)
WITH CHECK (true);

-- 6. Storage: receipts uploads stay public (anonymous checkout), reads are merchant-only
DROP POLICY IF EXISTS "anon_upload_receipts" ON storage.objects;
CREATE POLICY "anon_upload_receipts" ON storage.objects
FOR INSERT TO anon, authenticated
WITH CHECK (bucket_id = 'receipts');

DROP POLICY IF EXISTS "anon_read_receipts" ON storage.objects;
CREATE POLICY "anon_read_receipts" ON storage.objects
FOR SELECT TO anon USING (false);

DROP POLICY IF EXISTS "merchant_read_receipts" ON storage.objects;
CREATE POLICY "merchant_read_receipts" ON storage.objects
FOR SELECT TO authenticated
USING (bucket_id = 'receipts');

